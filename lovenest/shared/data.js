  /* marked.js 可用则配置; 不可用则降级为 <pre> 纯文本 */
  function ensureMarked() {
    if (typeof window.marked !== "undefined") {
      try {
        window.marked.setOptions({ breaks: true, gfm: true });
      } catch (e) {}
      return true;
    }
    return false;
  }

  /* 解析 md frontmatter (--- ... ---) 为对象, 返回 {meta, body} */
  function parseFrontmatter(text) {
    const meta = {};
    let body = text;
    const m = text.match(/^---\s*\n([\s\S]*?)\n---\s*\n?/);
    if (m) {
      body = text.slice(m[0].length);
      m[1].split("\n").forEach(line => {
        const idx = line.indexOf(":");
        if (idx < 0) return;
        const key = line.slice(0, idx).trim();
        let val = line.slice(idx + 1).trim();
        val = val.replace(/^["'](.*)["']$/, "$1");
        if (/^\[.*\]$/.test(val)) {
          val = val.slice(1, -1).split(",").map(s => s.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
        }
        if (key) meta[key] = val;
      });
    }
    return { meta, body };
  }

  /* 把 markdown 正文转成 HTML, 并追加 AI 解读 / 章节导航 UI */
  function renderMd(text) {
    const { meta, body } = parseFrontmatter(text);
    let html = "";
    if (ensureMarked()) {
      try { html = window.marked.parse(body); } catch (e) { html = ""; }
    }
    if (!html) html = "<pre>" + body.replace(/</g, "&lt;") + "</pre>";
    return wrapWithReadingUi(html);
  }

